public class DoWhile {
    public static void main(String[] args) {
        int n=0;
        int i=1;
        do{
            System.out.println("printing:"+i);
            i++;
        }
        while(i<=n);
    }
}
//the difference between the while and do while is in the while only the statements get executed if the condition is true but in the do while it will get executed atleast once even if the condition is not true
