public class Switch {
    public static void main(String[] args) {
        int val=1;
        switch (val) {
            case 1:
                System.out.println("monday");
                break;
            case 2:
                System.out.println("monday");
                break;
            default:
                System.out.println("not defined");
                break;
        }
    }   
}
