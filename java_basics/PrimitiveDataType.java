//java has 2 data types:primitive and reference
//There are 8 primitive data types 
/*
1byte-8bits

Integer:byte(8bit),short(16bit),int(32bit),long(64bit)
Float:float(4byte),double
Character:char(2byte)
Boolean:boolean
*/
public class PrimitiveDataType {
    public static void main(String[] args) {
        float marks = 6.5f;// by default point values are double need to put f for making the floatand also
                           // long needs l
        System.out.println(marks);
        char c = 'h';
        System.out.println(c);
        boolean val = true;
        System.out.println(val);
    }
}
